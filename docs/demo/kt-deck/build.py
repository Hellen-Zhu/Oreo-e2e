def inline(t):
    t = html.escape(t, quote=False)
    t = re.sub(r'`([^`]+)`', r'<code>\1</code>', t)
    t = re.sub(r'\*\*([^*]+)\*\*', r'<b>\1</b>', t)
    return t

def to_html(lines):
    out, lst, quote = [], None, False
    def close_list():
        nonlocal lst
        if lst: out.append(f'</{lst}>'); lst = None
    i = 0
    while i < len(lines):
        raw = lines[i]
        q = raw.startswith('>')
        s = raw[1:].strip() if q else raw.strip()
        if q != quote:
            close_list(); out.append('<blockquote>' if q else '</blockquote>'); quote = q
        if not s:
            close_list()
        elif s.startswith('|'):
            close_list()
            rows = []
            while i < len(lines) and lines[i].strip().startswith('|'):
                cells = [c.strip() for c in lines[i].strip().strip('|').split('|')]
                if not all(re.fullmatch(r'-+', c) for c in cells): rows.append(cells)
                i += 1
            out.append('<table>' + ''.join('<tr>' + ''.join(f'<{"th" if k == 0 else "td"}>{inline(c)}</{"th" if k == 0 else "td"}>' for c in r) + '</tr>' for k, r in enumerate(rows)) + '</table>')
            continue
        elif re.match(r'^(- |\d+\. )', s):
            kind = 'ul' if s.startswith('- ') else 'ol'
            if lst != kind: close_list(); out.append(f'<{kind}>'); lst = kind
            out.append('<li>' + inline(re.sub(r'^(- |\d+\. )', '', s)) + '</li>')
        elif s.startswith('#'):
            close_list(); out.append('<p class="sh">' + inline(s.lstrip('#').strip()) + '</p>')
        else:
            close_list(); out.append('<p>' + inline(s) + '</p>')
        i += 1
    close_list()
    if quote: out.append('</blockquote>')
    return '\n'.join(out)

def split(text, count):
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    slides, cur, pending = {}, None, []
    for line in text.splitlines():
        m = re.match(r'^\*\*\[翻页 (\d+)\]\s*(.*?)\*\*\s*(.*)$', line)
        if m:
            cur = int(m.group(1))
            slides[cur] = list(pending) if any(not l.startswith('#') and l.strip() for l in pending) else []
            if m.group(3).strip(): slides[cur].append(m.group(3).strip())
            pending = []
        elif line.startswith('# ') or line.strip() == '---':
            cur = None
        elif cur is None:
            if line.startswith('##') or line.strip() or pending: pending.append(line)
        else:
            if line.startswith('##'): cur = None; pending.append(line)
            else: slides[cur].append(line)
    if any(l.strip() and not l.startswith('#') for l in pending): slides[count].extend([''] + pending)
    missing = [n for n in range(1, count + 1) if n not in slides]
    assert not missing, f'no script for slides {missing}'
    return {n: to_html(v) for n, v in slides.items()}


